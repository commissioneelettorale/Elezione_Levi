'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),{spawnSync}=require('node:child_process');
const backend=fs.readFileSync('functions/core.js','utf8');
const frontend=fs.readFileSync('index.html','utf8');
const syntax=spawnSync(process.execPath,['--check','functions/core.js'],{encoding:'utf8'});
assert.equal(syntax.status,0,syntax.stderr);
const mod=frontend.match(/<script type="module">([\s\S]*?)<\/script>/);
assert.ok(mod,'Missing application script');
const jsCheck=spawnSync(process.execPath,['--input-type=module','--check'],{input:mod[1],encoding:'utf8'});
assert.equal(jsCheck.status,0,jsCheck.stderr);
const start=backend.indexOf('function technicalControlsOk(controls)');
const end=backend.indexOf('function privacyArchitectureAssessment',start);
assert.ok(start>=0&&end>start);
const sandbox={};vm.runInNewContext(backend.slice(start,end)+'\nthis.check=technicalControlsOk;',sandbox);
assert.equal(sandbox.check({backendReachable:true,firebaseReachable:true,serverSideAuth:true,firestoreFailClosed:null,regularityMissing:['privacyChecked'],testMode:true}),true,'A saved technical checkpoint is not conditioned on separate legal checks');
assert.equal(sandbox.check({backendReachable:true,firebaseReachable:false,serverSideAuth:true}),false);
const approval=backend.slice(backend.indexOf('exports.setRegularityControl ='),backend.indexOf('exports.recordResultsPublication ='));
assert.ok(approval.includes("report.data()?.result!=='PROVE_DICHIARATE_SUPERATE'"),'PASS report remains essential');
assert.ok(!approval.includes('LegalReadiness.structuralBlockers(config).length'),'Independent privacy is not an artificial technical-report gate');
assert.ok(backend.includes('...VotingAdmission.blockers(config,state,admissionBinding(config,state))'),'Admission still checks independent privacy requirements');
assert.ok(frontend.includes('Verifiche documentali confermate:'),'Commission progress separated');
assert.ok(frontend.includes('Rapporto già registrato'),'Report reuse enabled');
assert.ok(frontend.includes('fetchCompleteTechnicalLog()'),'History available');
console.log('PASS: report UI, backend syntax, independent technical checks and unchanged voting admission blockers.');
