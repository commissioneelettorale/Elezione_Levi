'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),{spawnSync}=require('node:child_process');
const html=fs.readFileSync('index.html','utf8');
const moduleSource=html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
assert.ok(moduleSource,'app module present');
const check=spawnSync(process.execPath,['--input-type=module','--check'],{input:moduleSource,encoding:'utf8'});
assert.equal(check.status,0,check.stderr);
const login=moduleSource.slice(moduleSource.indexOf('async function runCommissionLoginOnce()'),moduleSource.indexOf('function renderCommissionPasswordChange('));
assert.doesNotMatch(login,/startTokensListener\(\)/,'Commission login must not enumerate all tokens');
const changePassword=moduleSource.slice(moduleSource.indexOf('window.changeInitialCommissionPassword'),moduleSource.indexOf('function renderAdminPanel('));
assert.doesNotMatch(changePassword,/startTokensListener\(\)/,'Changing password must not enumerate all tokens');
assert.match(moduleSource,/const needsTokenRegister = activeAdminTab\?\.startsWith\('cred_'\) \|\| activeAdminTab === 'grafici'/);
assert.match(moduleSource,/if \(!needsTokenRegister\) stopTokensListener\(\)/);
assert.match(moduleSource,/if \(!unsubscribeTokens && !tokensListenerError\) startTokensListener\(\)/);
assert.match(moduleSource,/if \(unsubscribeTokens \|\| !auth\.currentUser \|\| !commissionSessionReady\) return/);
assert.match(moduleSource,/const unsub=unsubscribeTokens;[\s\S]*?unsub\(\)/);
assert.match(moduleSource,/window.logoutAdmin = function\(\) \{[\s\S]*?stopTokensListener\(\)/);
assert.match(moduleSource,/else if\(activeAdminTab\.startsWith\('cred_'\)\)/);
assert.match(moduleSource,/else if\(activeAdminTab === 'grafici'\)/);
console.log('PASS: app syntax, no full-registry listener at login, lazy authorized registry/chart loading, listener cleanup.');
