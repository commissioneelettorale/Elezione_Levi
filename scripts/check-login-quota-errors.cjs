'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const {spawnSync}=require('node:child_process');
const crypto=require('node:crypto');
const api=fs.readFileSync('api/call.js','utf8'),html=fs.readFileSync('index.html','utf8');
const check=(source,args)=>spawnSync(process.execPath,args,{input:source,encoding:'utf8'});
assert.equal(check(api,['--check']).status,0,'API JavaScript syntax');
const match=html.match(/<script type="module">([\s\S]*?)<\/script>/);
assert.ok(match,'App module exists');
const frontend=check(match[1],['--input-type=module','--check']);
assert.equal(frontend.status,0,frontend.stderr);
const start=api.indexOf('const STAFF_LOGIN_FUNCTIONS =');
const end=api.indexOf('let handlers;',start);
assert.ok(start>=0&&end>start);
const ctx={crypto};
vm.runInNewContext(api.slice(start,end)+'\nthis.throttle=rateLimitStaffLogin;',ctx);
const request={headers:{'x-forwarded-for':'192.0.2.50'}};
for(let i=0;i<12;i++)assert.equal(ctx.throttle(request,'commissionLogin'),null,'First 12 attempts allowed in a window');
const retry=ctx.throttle(request,'commissionLogin');
assert.ok(retry>0&&retry<=300,'Subsequent requests throttled locally');
assert.equal(ctx.throttle(request,'technicalLogin'),null,'Independent role limit');
assert.equal(ctx.throttle({headers:{'x-forwarded-for':'192.0.2.51'}},'commissionLogin'),null,'Independent source limit');
assert.ok(api.includes("code: 'too-many-requests'"),'Own throttle uses a distinct error code');
assert.ok(api.includes("retryAfterSeconds: retryAfter"),'Throttle returns remaining wait');
assert.ok(api.includes("'resource-exhausted': 429"),'Cloud provider errors retain distinct resource-exhausted code');
assert.ok(html.includes("authCode==='too-many-requests'"),'UI explains network login rate limit');
assert.ok(html.includes("authCode==='resource-exhausted'"),'UI explains actual Firebase error');
assert.ok(html.includes('commissionLoginInProgress'),'Duplicate concurrent Commission clicks blocked');
assert.ok(html.includes('commissionLoginCooldownUntil'),'Throttle wait enforced client-side');
assert.ok(!api.includes('error: { code: \'resource-exhausted\', message: \'Troppi tentativi'),'Own throttling not misreported as Firebase quota');
console.log('PASS: API/frontend syntax; 12/5-minute login throttle; distinct Firebase quota error; no automatic login retries.');
